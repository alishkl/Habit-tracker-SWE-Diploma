  }

  // Метод для форматирования строк с параметрами (например, %d)
  String getStringWithParams(String key, List<dynamic> params) {
    String value = getString(key);
    for (int i = 0; i < params.length; i++) {
      value = value.replaceAll('%d', params[i].toString());
    }
    return value;
  }
